-- Public clinic details are readable by everyone (anonymous site visitors).
create policy "clinic_public_settings_public_read" on public.clinic_public_settings
  for select using (true);
create policy "clinic_public_settings_admin_write" on public.clinic_public_settings
  for all using (public.is_trusted_admin()) with check (public.is_trusted_admin());

-- Users may read/update their own profile; trusted admins manage all rows.
create policy "users_own_read" on public.users
  for select using (public.current_profile_email() = email or public.is_trusted_admin());
create policy "users_own_update" on public.users
  for update using (public.current_profile_email() = email or public.is_trusted_admin())
  with check (public.current_profile_email() = email or public.is_trusted_admin());

-- Clinic workflow tables: trusted admins only. The app's OAuth gate in
-- server/clinic-authority.ts remains the primary authorization layer; these
-- policies add a second guard when Supabase Auth is used for sign-in.
do $$
declare t text;
begin
  foreach t in array array[
    'super_admin_audit_events','super_admin_governance_settings','super_admin_access_reviews',
    'referral_audit_events','referral_retry_counters','referral_delivery_monitor',
    'audit_retention_policies','audit_archive_runs','audit_retention_policy_changes',
    'guardian_contacts','patient_report_shares','waitlist_requests','waitlist_event_log',
    'staff_capacity_snapshots','internal_follow_up_print_audits','capacity_target_change_alerts',
    'print_audit_filter_presets','capacity_alert_visibility_settings','clinic_staff_accounts',
    'weekly_capacity_summary_exports','invitation_search_presets',
    'weekly_capacity_report_reference_settings','staff_invitation_settings',
    'staff_account_activity','clinic_appointments','clinic_day_hour_overrides',
    'guardian_record_access_challenges'
  ]
  loop
    execute format('create policy %I on public.%I for select using (public.is_trusted_admin())', 'rls_' || t || '_read', t);
    execute format('create policy %I on public.%I for insert with check (public.is_trusted_admin())', 'rls_' || t || '_insert', t);
    execute format('create policy %I on public.%I for update using (public.is_trusted_admin()) with check (public.is_trusted_admin())', 'rls_' || t || '_update', t);
    execute format('create policy %I on public.%I for delete using (public.is_trusted_admin())', 'rls_' || t || '_delete', t);
  end loop;
end $$;
