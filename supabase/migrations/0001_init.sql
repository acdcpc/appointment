-- Trusted authority helpers (keys to Supabase Auth email; kept in sync with
-- server/clinic-authority.ts).
create or replace function public.is_super_admin()
returns boolean language sql stable as $$
  select auth.jwt()->>'email' = 'thisispratha@gmail.com';
$$;

create or replace function public.is_clinic_admin()
returns boolean language sql stable as $$
  select auth.jwt()->>'email' = 'anilrajojha@pahs.edu.np'
      or exists (
        select 1 from public.users u
        where u.email = auth.jwt()->>'email'
          and u.role = 'admin'
      );
$$;

create or replace function public.is_trusted_admin()
returns boolean language sql stable as $$
  select public.is_super_admin() or public.is_clinic_admin();
$$;

create or replace function public.current_profile_email()
returns text language sql stable as $$
  select nullif(auth.jwt()->>'email', '')::text;
$$;


-- ============================= UPDATED_AT TRIGGERS =============================
do $$
declare t text;
begin
  foreach t in array array[
    'users','super_admin_governance_settings','referral_retry_counters','referral_delivery_monitor',
    'audit_retention_policies','clinic_public_settings','guardian_contacts','waitlist_requests',
    'print_audit_filter_presets','capacity_alert_visibility_settings','clinic_staff_accounts',
    'invitation_search_presets','weekly_capacity_report_reference_settings','staff_invitation_settings',
    'clinic_appointments','clinic_day_hour_overrides'
  ]
  loop
    execute format('drop trigger if exists trg_%I_updated_at on public.%I', t, t);
    execute format('create trigger trg_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', t, t);
  end loop;
end $$;

